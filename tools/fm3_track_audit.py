"""fm3_track_audit.py: how far the track tools get on every FM3 track (PLAN-CARS.md phase 5, the audit).

    python tools/fm3_track_audit.py <extracted tracks dir> <Media\\Tracks dir> [--out out/manifest/track_audit.md]

<extracted tracks dir>/<track>/ = Media\\Tracks\\<Track>\\bin.zip extracted (tools\\fm3unzip\\fm3unzip.exe); CrownJewel may
also be work\\assets\\crownjewel (found by --extra name=dir). Per track it reports:
  - model files (.rmb.bin): read by the sequential parser (fm3_track.parse with its material table), only by the
    fallback name scanner, or not at all;
  - meshes by shader (the file's 'shaders\\track\\...' list indexed by its material table): drawn by a family recipe
    (fm3_families.recipe), plain (one base texture: the export's default), or multi-texture with no recipe (would fall
    back to the base texture: the area to fix);
  - vertex strides without a known layout (fm3_track.LAYOUTS);
  - each ribbon's .pvs: version, instances, models, textures (fm3_pvs.parse), or its error;
  - whether staticcarcubemap.xpr and TrackSettings.xml are there.
Writes a Markdown report (no game data in it) and prints the summary.
"""
import collections
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fm3_families  # noqa: E402
import fm3_pvs  # noqa: E402
import fm3_track  # noqa: E402

MULTI = re.compile(r'blnd|_mix|mask|4clr|ovly')


def audit_track(src, media):
    r = {'files': 0, 'seq': 0, 'scan': 0, 'fail': 0, 'meshes': 0, 'family': 0, 'plain': 0, 'nofam': 0,
         'nofam_shaders': collections.Counter(), 'family_shaders': collections.Counter(),
         'bad_strides': collections.Counter(), 'pvs': [], 'cube': False, 'settings': False, 'errors': []}
    for path in sorted(glob.glob(os.path.join(src, '*.rmb.bin'))):
        r['files'] += 1
        data = open(path, 'rb').read()
        try:
            model = fm3_track.parse(data)
        except Exception as e:  # noqa: BLE001 (a report of what fails)
            r['fail'] += 1
            if len(r['errors']) < 5:
                r['errors'].append(f'{os.path.basename(path)}: {type(e).__name__} {e}')
            continue
        if 'materials' in model:
            r['seq'] += 1
        else:
            r['scan'] += 1
        shaders = [x.decode() for x in re.findall(rb'shaders\\track\\([a-z0-9_]+)', data)]
        mats = model.get('materials') or []
        for me in model['meshes']:
            r['meshes'] += 1
            if me['stride'] not in fm3_track.LAYOUTS:
                r['bad_strides'][me['stride']] += 1
            mi = me.get('material_index', 99999)
            if mi >= len(mats):
                r['plain'] += 1
                continue
            mt = mats[mi]
            shn = shaders[mt['shader']] if mt['shader'] < len(shaders) else ''
            rec = fm3_families.recipe(shn, mt['params'], me['stride'], mt['slots'])
            if rec is not None:
                r['family'] += 1
                r['family_shaders'][shn] += 1
            elif MULTI.search(shn):
                r['nofam'] += 1
                r['nofam_shaders'][f'{shn} (stride {me["stride"]})'] += 1
            else:
                r['plain'] += 1
    if media and os.path.isdir(media):
        names = {f.lower() for f in os.listdir(media)}
        r['cube'] = 'staticcarcubemap.xpr' in names
        r['settings'] = 'tracksettings.xml' in names
        for pvs in sorted(glob.glob(os.path.join(media, 'Ribbon_*', '*.pvs'))):
            try:
                pv = fm3_pvs.parse(open(pvs, 'rb').read())
                r['pvs'].append((os.path.basename(pvs), pv.get('version'), len(pv['instances']), len(pv['models']),
                                 len(pv['textures'])))
            except Exception as e:  # noqa: BLE001
                r['pvs'].append((os.path.basename(pvs), f'error: {type(e).__name__} {e}', 0, 0, 0))
    return r


def main():
    a = sys.argv[1:]
    out = a[a.index('--out') + 1] if '--out' in a else None
    extra = {}
    for i, x in enumerate(a):
        if x == '--extra':
            k, v = a[i + 1].split('=', 1)
            extra[k.lower()] = v
    pos = [x for i, x in enumerate(a) if not x.startswith('--') and (i == 0 or a[i - 1] not in ('--out', '--extra'))]
    tracks_dir, media_dir = pos[0], pos[1]
    names = sorted({d.lower() for d in os.listdir(tracks_dir) if os.path.isdir(os.path.join(tracks_dir, d))} | set(extra))
    media = {d.lower(): os.path.join(media_dir, d) for d in os.listdir(media_dir)}
    lines = ['# FM3 track audit', '',
             'Generated by `tools/fm3_track_audit.py` (PLAN-CARS.md phase 5). Meshes: drawn by a shader-family recipe, '
             'plain (one base texture), or multi-texture with no recipe (falls back to its base texture).', '',
             '| track | model files | sequential / scan / failed | meshes | family | plain | no recipe | unknown strides '
             '| ribbons (.pvs v, instances) | cube | settings |',
             '|---|---|---|---|---|---|---|---|---|---|---|']
    all_nofam = collections.Counter()
    tot = collections.Counter()
    for t in names:
        src = extra.get(t, os.path.join(tracks_dir, t))
        r = audit_track(src, media.get(t))
        for k in ('files', 'seq', 'scan', 'fail', 'meshes', 'family', 'plain', 'nofam'):
            tot[k] += r[k]
        all_nofam.update({f'{t}: {k}': v for k, v in r['nofam_shaders'].items()})
        pv = ', '.join(f'v{p[1]} {p[2]}' for p in r['pvs'][:3]) + (f' (+{len(r["pvs"]) - 3})' if len(r['pvs']) > 3 else '')
        strides = ', '.join(f'{k} x{v}' for k, v in sorted(r['bad_strides'].items())) or '-'
        pct = lambda n: f'{100.0 * n / max(1, r["meshes"]):.1f} %'  # noqa: E731
        lines.append(f'| {t} | {r["files"]} | {r["seq"]} / {r["scan"]} / {r["fail"]} | {r["meshes"]} | {pct(r["family"])} '
                     f'| {pct(r["plain"])} | {pct(r["nofam"])} | {strides} | {len(r["pvs"])}: {pv} '
                     f'| {"yes" if r["cube"] else "no"} | {"yes" if r["settings"] else "no"} |')
        print(f'{t:14s} files {r["files"]:5d} (seq {r["seq"]}, scan {r["scan"]}, fail {r["fail"]}), meshes {r["meshes"]}, '
              f'family {pct(r["family"])}, no recipe {pct(r["nofam"])}, strides {strides}, ribbons {len(r["pvs"])}'
              + (f'; errors: {r["errors"][:2]}' if r['errors'] else ''))
    lines += ['', f'Total: {tot["files"]} model files ({tot["seq"]} sequential, {tot["scan"]} scan only, {tot["fail"]} failed), '
              f'{tot["meshes"]} meshes: {100.0 * tot["family"] / max(1, tot["meshes"]):.1f} % by a family recipe, '
              f'{100.0 * tot["nofam"] / max(1, tot["meshes"]):.1f} % multi-texture without one.', '',
              '## Multi-texture shaders without a recipe (meshes)', '']
    for k, v in all_nofam.most_common(40):
        lines.append(f'- {k}: {v}')
    print(f'TOTAL files {tot["files"]} seq {tot["seq"]} scan {tot["scan"]} fail {tot["fail"]} meshes {tot["meshes"]} '
          f'family {tot["family"]} plain {tot["plain"]} no recipe {tot["nofam"]}')
    if out:
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, 'w', newline='\n') as f:
            f.write('\n'.join(lines) + '\n')
        print('report:', out)


if __name__ == '__main__':
    main()
